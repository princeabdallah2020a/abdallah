#!/usr/bin/env python3
"""Authoring helper (NOT needed to run the prototype): assembles index/search/vehicle.html and js/i18n.js
from _src/partials, _src/pages and _src/strings.py.  Run: python3 -I _src/gen_tokens.py && python3 -I _src/gen_logo.py && python3 -I _src/build.py"""
import json, re, pathlib, sys, html
here = pathlib.Path(__file__).resolve().parent
out = here.parent
sys.path.insert(0, str(here))
from strings import S   # key -> (fr, en, ar)

P = lambda n: (here/'partials'/n).read_text()
L = json.loads((here/'logo_paths.json').read_text())

def logo(suffix):
    W, top, bottom = L['width'], -1500, 520
    cx, cy, r = L['sun'][0], -L['sun'][1], L['sun'][2]
    gy0 = cy - r + 0.62*2*r; gy1 = gy0 + 2*r*3/40
    paths = ''.join(f'<path d="{d}"/>' for d in L['paths'])
    return (f'<svg class="wy-logo__svg" viewBox="0 {top} {W:.0f} {bottom-top}" role="img" focusable="false"><title>Wotoyi</title>'
      f'<defs><linearGradient id="wy-sun-{suffix}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" style="stop-color:var(--wy-logo-a)"/><stop offset="1" style="stop-color:var(--wy-logo-b)"/></linearGradient>'
      f'<clipPath id="wy-sunt-{suffix}"><rect x="{cx-r-5:.0f}" y="{cy-r-5:.0f}" width="{2*r+10:.0f}" height="{gy0-(cy-r)+5:.0f}"/></clipPath>'
      f'<clipPath id="wy-sunb-{suffix}"><rect x="{cx-r-5:.0f}" y="{gy1:.0f}" width="{2*r+10:.0f}" height="{cy+r-gy1+5:.0f}"/></clipPath></defs>'
      f'<g fill="currentColor">{paths}</g>'
      f'<circle cx="{cx:.0f}" cy="{cy:.0f}" r="{r:.0f}" fill="url(#wy-sun-{suffix})" clip-path="url(#wy-sunt-{suffix})"/>'
      f'<circle cx="{cx:.0f}" cy="{cy:.0f}" r="{r:.0f}" fill="url(#wy-sun-{suffix})" opacity=".7" clip-path="url(#wy-sunb-{suffix})"/></svg>')

seg_n = [0]
def theme_seg():
    seg_n[0] += 1; n = seg_n[0]
    return (f'<div class="wy-segmented wy-segmented--sm" role="radiogroup" aria-label="{{{{=theme.label}}}}" data-i18n-attr="aria-label:theme.label">'
            + ''.join(f'<label><input type="radio" name="wy-theme-{n}" value="{v}" data-wy-theme-radio><span>{{{{theme.{v}}}}}</span></label>' for v in ('auto', 'light', 'dark')) + '</div>')

missing = set()
def esc_attr(s): return s.replace('"', '&quot;')
def subst(t):
    def opt(m):
        k = m.group(2)
        if k not in S: missing.add(k); return m.group(0)
        return f'<option{m.group(1)} data-i18n="{k}">{S[k][0]}</option>'
    t = re.sub(r'<option([^>]*)>\{\{([a-zA-Z0-9_.]+)\}\}</option>', opt, t)
    def attr(m):
        k = m.group(1)
        if k not in S: missing.add(k); return m.group(0)
        return esc_attr(S[k][0])
    t = re.sub(r'\{\{=([a-zA-Z0-9_.]+)\}\}', attr, t)
    def txt(m):
        k = m.group(1)
        if k not in S: missing.add(k); return m.group(0)
        return f'<span data-i18n="{k}">{S[k][0]}</span>'
    return re.sub(r'\{\{([a-zA-Z0-9_.]+)\}\}', txt, t)

PAGES = {
  'index.html':   ('home',   'title.home',   'desc.home',   ' data-tone="night"', 'home.html'),
  'search.html':  ('search', 'title.search', 'desc.search', '', 'search.html'),
  'vehicle.html': ('vehicle','title.vehicle','desc.vehicle','', 'vehicle.html'),
}
for fn, (page, tk, dk, hattr, body) in PAGES.items():
    head = P('head.html').replace('%%TITLE%%', esc_attr(S[tk][0])).replace('%%DESC%%', esc_attr(S[dk][0]))
    header = (P('header.html').replace('%%PAGE%%', page).replace('%%SPRITE%%', P('sprite.html')).replace('%%HEADERATTR%%', hattr)
              .replace('%%LOGO_H%%', logo('h')).replace('%%THEMESEG%%', theme_seg()))
    footer = P('footer.html').replace('%%LOGO_F%%', logo('f')).replace('%%THEMESEG%%', theme_seg())
    main = (here/'pages'/body).read_text()
    scripts = ('<script src="js/i18n.js"></script>\n<script src="js/data.js"></script>\n<script src="js/motion.js"></script>\n'
               '<script src="js/app.js"></script>\n<script src="js/%s.js"></script>\n' % page)
    doc = head + header + main + footer + scripts + '</body>\n</html>\n'
    (out/fn).write_text(subst(doc))
    print('wrote', fn, len((out/fn).read_text()), 'bytes')

# i18n.js: strings + apply logic is in js/i18n.core.js (hand-written); concatenated here
core = (out/'js'/'i18n.core.js').read_text() if (out/'js'/'i18n.core.js').exists() else ''
data = {lang: {k: v[i] for k, v in S.items()} for i, lang in enumerate(('fr', 'en', 'ar'))}
(out/'js'/'i18n.js').write_text('/* GENERATED by _src/build.py from _src/strings.py. EN/AR are demo translations, not natively reviewed. */\nwindow.WY_STR=' + json.dumps(data, ensure_ascii=False) + ';\n' + core)
if missing:
    print('MISSING KEYS:', sorted(missing)); sys.exit(1)
print('strings:', len(S))
